use thiserror::Error;

// =========================================================================
// Shared Domain Error — unified error conversion chain
// =========================================================================
//
// Every app-level `AppError` can `#[from]` this, creating a seamless
// error conversion pipeline: newtype parse errors → DomainError → AppError.

/// Validation error for satellite IDs (generated by `define_newtype_id!`).
#[derive(Debug, Error)]
pub enum SatelliteIdError {
    #[error("Satellite ID must start with 'SAT-', got: {0}")]
    InvalidPrefix(String),
    #[error("Satellite ID numeric part is invalid: {0}")]
    InvalidNumber(String),
    #[error("Satellite ID number {0} out of range 1-9999")]
    OutOfRange(u16),
}

/// Validation error for ground station IDs.
#[derive(Debug, Error)]
pub enum StationIdError {
    #[error("Station ID must start with 'GS-', got: {0}")]
    InvalidPrefix(String),
    #[error("Station ID format is invalid: {0}")]
    InvalidFormat(String),
}

/// Validation error for mission IDs.
#[derive(Debug, Error)]
pub enum MissionIdError {
    #[error("Mission ID must start with 'MISSION-', got: {0}")]
    InvalidPrefix(String),
    #[error("Mission ID format is invalid: {0}")]
    InvalidFormat(String),
}

/// Shared domain error type that unifies all validation and lookup errors.
///
/// Each service's `AppError` should include:
/// ```ignore
/// #[error(transparent)]
/// Domain(#[from] orbitlogs_models::DomainError),
/// ```
///
/// This creates a seamless error conversion chain:
/// `SatelliteIdError` → `DomainError` → `AppError` via the `?` operator.
#[derive(Debug, Error)]
pub enum DomainError {
    #[error("Invalid satellite ID: {0}")]
    InvalidSatelliteId(#[from] SatelliteIdError),

    #[error("Invalid station ID: {0}")]
    InvalidStationId(#[from] StationIdError),

    #[error("Invalid mission ID: {0}")]
    InvalidMissionId(#[from] MissionIdError),

    #[error("Validation failed: {0:?}")]
    Validation(Vec<String>),

    #[error("Not found: {entity} with id {id}")]
    NotFound { entity: &'static str, id: String },
}
