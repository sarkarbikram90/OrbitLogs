pub fn generate_rule_response(
    query: &str,
    sat_id: &str,
    telemetry: Option<serde_json::Value>,
    events: &[serde_json::Value],
    commands: &[serde_json::Value],
) -> String {
    let query_lower = query.to_lowercase();
    let temp = telemetry
        .as_ref()
        .and_then(|t| t["temperature"].as_f64())
        .unwrap_or(25.0);
    let fuel = telemetry
        .as_ref()
        .and_then(|t| t["fuel_remaining"].as_f64())
        .unwrap_or(100.0);
    let battery = telemetry
        .as_ref()
        .and_then(|t| t["battery_voltage"].as_f64())
        .unwrap_or(13.8);

    if query_lower.contains("conjunction")
        || query_lower.contains("collision")
        || query_lower.contains("avoidance")
        || query_lower.contains("debris")
    {
        return format!(
            "### 🚨 Autonomous Collision Avoidance Recommendation for **{}**\n\n\
             **Conjunction Threat Analysis:**\n\
             - **Secondary Object**: `DEB-41920` (SL-8 Debris Cloud Fragment)\n\
             - **Time of Closest Approach (TCA)**: `T+ 01:24:15 UTC`\n\
             - **Current Miss Distance**: **412.5 meters** (Radial: 85m, In-Track: 310m, Cross-Track: 240m)\n\
             - **Calculated Probability of Collision ($P_c$)**: **$3.82 \\times 10^{{-3}}$** (CRITICAL)\n\n\
             **Recommended Collision Avoidance Maneuver (CAM):**\n\
             - **Burn Type**: In-Track Prograde Firing (`+0.45 m/s` $\\Delta v$)\n\
             - **Execution Window**: 45 minutes prior to TCA\n\
             - **Post-Burn Miss Distance**: **6.82 km** ($P_c < 10^{{-7}}$)\n\n\
             **Mission Impact Analysis:**\n\
             - **Propellant Cost**: **0.42 kg** ({:.1}% fuel remaining after burn)\n\
             - **Payload Downtime**: 15 minutes (Payload sensor placed in Standby)\n\
             - **Downlink Disruptions**: None (Ground station pass aligned post-burn)\n\n\
             *Recommendation generated by Space Traffic Management Copilot (DOC-SSA-201)*",
            sat_id,
            fuel - 0.42
        );
    }

    if query.contains("unhealthy") || query.contains("why") || query.contains("status") {
        let mut reasons = Vec::new();
        if temp > 80.0 {
            reasons.push(format!(
                "Subsystem temperature is critically high at **{:.1}°C** (limit: 80.0°C).",
                temp
            ));
        }
        if fuel < 15.0 {
            reasons.push(format!("Propellant supply is low at **{:.1}%**.", fuel));
        }
        if battery < 11.5 {
            reasons.push(format!(
                "Battery bank voltage is degraded at **{:.1}V**.",
                battery
            ));
        }

        let anomaly_desc = if !reasons.is_empty() {
            reasons.join("\n- ")
        } else {
            "All core subsystems are operating within normal telemetry ranges.".to_string()
        };

        let recommendations = if temp > 80.0 {
            "**Recommended Actions (per THERMAL RUNBOOK DOC-TH-099):**\n\
             1. **Orient yaw axis** to point heat shields directly at the sun vector.\n\
             2. **Shed payload power draw** (issue command `SHUTDOWN_PAYLOAD`).\n\
             3. Monitor telemetry loops closely for thermal stabilization."
        } else if battery < 11.5 {
            "**Recommended Actions (per BATTERY RUNBOOK DOC-EPS-104):**\n\
             1. Ensure solar panels are tracking at optimal sun-incidence angle.\n\
             2. Shut down secondary instrumentation heaters."
        } else {
            "No immediate operator remediation actions required."
        };

        format!(
            "### AI Diagnostics Summary for **{}**\n\n\
             **Subsystem Status:** {}\n\
             {}\n\n\
             **Recent Anomalies / Events:**\n{}\n\n\
             {}\n\n\
             *Generated by OrbitLogs Flight Ops AI Copilot*",
            sat_id,
            if !reasons.is_empty() {
                "DEGRADED / CRITICAL"
            } else {
                "NOMINAL"
            },
            anomaly_desc,
            if events.is_empty() {
                "No recent critical anomalies are found."
            } else {
                "Anomalies are found in last 24h."
            },
            recommendations
        )
    } else if query.contains("summarize")
        || query.contains("briefing")
        || query.contains("24 hours")
    {
        format!(
            "### Operator Handover Briefing: Constellation Status\n\n\
             - **Active Assets Monitored**: 10 Satellites (SAT-0001 through SAT-0010)\n\
             - **Overall Fleet Readiness**: Nominal\n\
             - **Target Analysis ({})**:\n\
               - Core Temperature: {:.1}°C\n\
               - Battery Level: {:.1}V\n\
               - Fuel Remaining: {:.1}%\n\n\
             **Recent Operations Log:**\n\
             - Uplinked {} commands in the last 2 hours.\n\
             - No new collision threats or orbital trajectory deviations detected.\n",
            sat_id,
            temp,
            battery,
            fuel,
            commands.len()
        )
    } else if query.contains("postmortem") || query.contains("report") {
        format!(
            "# Incident Postmortem Report\n\n\
             **Incident Asset:** {}\n\
             **Timestamp:** {}\n\n\
             ## Executive Summary\n\
             A transient thermal spike anomaly was registered on subsystem `thermal`. Temperature reached **{:.1}°C**, triggering critical telemetry alerts.\n\n\
             ## Root Cause Analysis\n\
             High-power payload duty cycles coupled with a solar array orientation maneuver resulted in transient heat trap. Avionics processor throttled to protect components.\n\n\
             ## Resolution Actions\n\
             Uplinked cold space pointing yaw command. Normal thermal margins restored.\n\n\
             *Report compiled automatically by OrbitLogs AI Incident Commander*",
            sat_id,
            chrono::Utc::now().to_rfc3339(),
            temp
        )
    } else {
        "Hello, Operator. I am your Space Operations AI Copilot. I have access to live telemetry, incident history, and standard runbooks. Ask me about asset diagnostics, anomaly causes, or summaries.".to_string()
    }
}
